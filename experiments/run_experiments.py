def run_locust_headless(
    host: str,
    users: int,
    spawn_rate: int,
    duration_seconds: int,
    csv_prefix: Path,
    profile: str = "mixed",
    strategy: str = "atomic_update",
    item_count: int = 20,
) -> bool:
    """Execute a headless Locust load test run and export CSV metrics."""
    csv_prefix.parent.mkdir(parents=True, exist_ok=True)

    env = os.environ.copy()
    env["LOADTEST_PROFILE"] = profile
    env["LOADTEST_STRATEGY"] = strategy
    env["LOADTEST_ITEM_COUNT"] = str(item_count)

    cmd = [
        sys.executable,
        "-m",
        "locust",
        "-f",
        "load_tests/locustfile.py",
        "--headless",
        "-u",
        str(users),
        "-r",
        str(spawn_rate),
        "-t",
        f"{duration_seconds}s",
        "--host",
        host,
        "--csv",
        str(csv_prefix),
        "--only-summary",
    ]

    logger.info(
        "Launching Locust run: profile=%s, strategy=%s, users=%d, duration=%ds",
        profile,
        strategy,
        users,
        duration_seconds,
    )

    try:
        proc = subprocess.run(
            cmd,
            env=env,
            capture_output=True,
            text=True,
            timeout=duration_seconds + 30,
        )
        if proc.returncode != 0:
            logger.warning("Locust exited with non-zero code %d: %s", proc.returncode, proc.stderr)
        return True
    except subprocess.TimeoutExpired:
        logger.error("Locust run timed out after %d seconds.", duration_seconds + 30)
        return False
    except Exception as e:
        logger.error("Failed to execute Locust load test: %s", e)
        return False


def parse_locust_stats(csv_prefix: Path) -> Dict[str, Any]:
    """Parse output CSV files generated by Locust."""
    stats_file = Path(f"{csv_prefix}_stats.csv")
    failures_file = Path(f"{csv_prefix}_failures.csv")

    metrics: Dict[str, Any] = {
        "total_requests": 0,
        "successful_requests": 0,
        "failed_requests": 0,
        "failure_rate": 0.0,
        "requests_per_second": 0.0,
        "avg_latency_ms": 0.0,
        "p50_latency_ms": 0.0,
        "p95_latency_ms": 0.0,
        "p99_latency_ms": 0.0,
        "min_latency_ms": 0.0,
        "max_latency_ms": 0.0,
        "endpoints": [],
        "failures": [],
    }

    if stats_file.exists():
        import pandas as pd

        try:
            df = pd.read_csv(stats_file)
            # Find the Aggregated row
            agg_row = df[df["Name"] == "Aggregated"]
            if not agg_row.empty:
                row = agg_row.iloc[0]
                total = int(row.get("Request Count", 0))
                fails = int(row.get("Failure Count", 0))
                metrics["total_requests"] = total
                metrics["failed_requests"] = fails
                metrics["successful_requests"] = total - fails
                metrics["failure_rate"] = round((fails / total * 100.0) if total > 0 else 0.0, 2)
                metrics["requests_per_second"] = round(float(row.get("Requests/s", 0.0)), 2)
                metrics["avg_latency_ms"] = round(float(row.get("Average Response Time", 0.0)), 2)
                metrics["min_latency_ms"] = round(float(row.get("Min Response Time", 0.0)), 2)
                metrics["max_latency_ms"] = round(float(row.get("Max Response Time", 0.0)), 2)
                metrics["p50_latency_ms"] = round(float(row.get("50%", 0.0)), 2)
                metrics["p95_latency_ms"] = round(float(row.get("95%", 0.0)), 2)
                metrics["p99_latency_ms"] = round(float(row.get("99%", 0.0)), 2)

            # Endpoint-level details
            ep_rows = df[df["Name"] != "Aggregated"]
            for _, r in ep_rows.iterrows():
                metrics["endpoints"].append({
                    "name": str(r.get("Name", "")),
                    "method": str(r.get("Type", "")),
                    "requests": int(r.get("Request Count", 0)),
                    "failures": int(r.get("Failure Count", 0)),
                    "rps": round(float(r.get("Requests/s", 0.0)), 2),
                    "avg_ms": round(float(r.get("Average Response Time", 0.0)), 2),
                    "p50_ms": round(float(r.get("50%", 0.0)), 2),
                    "p95_ms": round(float(r.get("95%", 0.0)), 2),
                    "p99_ms": round(float(r.get("99%", 0.0)), 2),
                })
        except Exception as e:
            logger.warning("Could not parse locust stats CSV: %s", e)

    if failures_file.exists():
        import pandas as pd
        try:
            fdf = pd.read_csv(failures_file)
            for _, fr in fdf.iterrows():
                metrics["failures"].append({
                    "method": str(fr.get("Method", "")),
                    "name": str(fr.get("Name", "")),
                    "error": str(fr.get("Error", "")),
                    "occurrences": int(fr.get("Occurrences", 0)),
                })
        except Exception as e:
            logger.warning("Could not parse locust failures CSV: %s", e)

    return metrics


def execute_matrix(
    config_path: Path = Path("experiments/config.yaml"),
    smoke: bool = False,
    quick: bool = False,
) -> List[Dict[str, Any]]:
    """Execute complete reproducible experiment matrix."""
    with open(config_path, "r", encoding="utf-8") as f:
        cfg = yaml.safe_load(f)

    target_host = cfg.get("target_host", "http://127.0.0.1:8000")
    results_base = Path("results")
    results_base.mkdir(exist_ok=True)

    if smoke or quick:
        concurrencies = cfg.get("smoke_test", {}).get("concurrency_levels", [5, 20])
        profiles = cfg.get("smoke_test", {}).get("workload_profiles", ["mixed", "write_heavy"])
        strategies = cfg.get("smoke_test", {}).get("strategies", ["atomic_update", "pessimistic_lock"])
        duration = cfg.get("smoke_test", {}).get("duration_seconds", 5)
        repetitions = cfg.get("smoke_test", {}).get("repetitions", 1)
    else:
        concurrencies = cfg.get("concurrency_levels", [5, 20, 50, 100])
        profiles = cfg.get("workload_profiles", ["mixed", "read_heavy", "write_heavy", "spike"])
        strategies = cfg.get("concurrency_strategies", ["atomic_update", "pessimistic_lock"])
        duration = cfg.get("default_duration_seconds", 12)
        repetitions = cfg.get("repetitions", 2)

    item_count = cfg.get("default_item_count", 20)
    initial_inventory = cfg.get("default_initial_inventory", 200)

    # 1. Run Query Plan Analysis for Indexing Comparisons
    logger.info("Executing Query Plan Analysis (Index vs Baseline)...")
    run_query_plan_comparison(results_base / "indexed")

    experiment_records: List[Dict[str, Any]] = []

    # 2. Iterate through experiment matrix
    for strategy in strategies:
        category_dir = results_base / strategy
        category_dir.mkdir(parents=True, exist_ok=True)

        for profile in profiles:
            for concurrency in concurrencies:
                for rep in range(1, repetitions + 1):
                    run_tag = f"{strategy}_{profile}_c{concurrency}_rep{rep}"
                    logger.info("Starting Run: %s", run_tag)

                    # Step A: Seed Database
                    seed_database(item_count=item_count, initial_inventory_per_item=initial_inventory)

                    # Step B: Pre-run consistency verification
                    pre_check = run_consistency_audit()
                    if not pre_check["consistent"]:
                        logger.error("Pre-run database consistency failed! Aborting run %s", run_tag)
                        continue

                    # Step C: Execute Load Test
                    csv_prefix = category_dir / run_tag
                    t_start = time.time()
                    spawn_rate = max(5, concurrency // 2)
                    success = run_locust_headless(
                        host=target_host,
                        users=concurrency,
                        spawn_rate=spawn_rate,
                        duration_seconds=duration,
                        csv_prefix=csv_prefix,
                        profile=profile,
                        strategy=strategy,
                        item_count=item_count,
                    )
                    t_end = time.time()

                    # Step D: Post-workload consistency verification
                    post_check = run_consistency_audit(output_dir=category_dir, tag=run_tag)

                    # Step E: Parse metrics
                    metrics = parse_locust_stats(csv_prefix)

                    record = {
                        "run_tag": run_tag,
                        "strategy": strategy,
                        "profile": profile,
                        "concurrency": concurrency,
                        "repetition": rep,
                        "duration_seconds": duration,
                        "started_at": t_start,
                        "completed_at": t_end,
                        "locust_success": success,
                        "consistency_passed": post_check["consistent"],
                        "violations_count": post_check["violations_count"],
                        "metrics": metrics,
                        "post_check": {
                            "active_reservations": post_check["active_reservations"],
                            "released_reservations": post_check["released_reservations"],
                            "violations": post_check["violations"],
                        },
                    }

                    # Persist record JSON
                    with open(category_dir / f"{run_tag}_summary.json", "w", encoding="utf-8") as f:
                        json.dump(record, f, indent=2)

                    experiment_records.append(record)

                    # Record in DB
                    try:
                        session_factory = get_session_factory()
                        db = session_factory()
                        exp_run = ExperimentRun(
                            scenario=f"{strategy}_{profile}",
                            strategy=strategy,
                            concurrency=concurrency,
                            request_count=metrics["total_requests"],
                            consistency_passed=post_check["consistent"],
                        )
                        db.add(exp_run)
                        db.commit()
                        db.close()
                    except Exception as e:
                        logger.warning("Could not record ExperimentRun to DB: %s", e)

    # 3. Connection Pool Benchmarks
    pool_cfgs = cfg.get("pool_configurations", [])
    pool_dir = results_base / "pool_tuned"
    pool_dir.mkdir(parents=True, exist_ok=True)
    for pcfg in pool_cfgs:
        p_name = pcfg["name"]
        run_tag = f"pool_{p_name}_c50"
        logger.info("Executing Pool Benchmark Configuration: %s", p_name)

        seed_database(item_count=item_count, initial_inventory_per_item=initial_inventory)
        csv_prefix = pool_dir / run_tag

        run_locust_headless(
            host=target_host,
            users=min(50, max(concurrencies)),
            spawn_rate=10,
            duration_seconds=duration,
            csv_prefix=csv_prefix,
            profile="mixed",
            strategy="atomic_update",
            item_count=item_count,
        )
        post_check = run_consistency_audit(output_dir=pool_dir, tag=run_tag)
        metrics = parse_locust_stats(csv_prefix)

        precord = {
            "run_tag": run_tag,
            "pool_config": pcfg,
            "strategy": "atomic_update",
            "profile": "mixed",
            "concurrency": min(50, max(concurrencies)),
            "consistency_passed": post_check["consistent"],
            "metrics": metrics,
        }
        with open(pool_dir / f"{run_tag}_summary.json", "w", encoding="utf-8") as f:
            json.dump(precord, f, indent=2)
        experiment_records.append(precord)

    # Save overall master runs list
    with open(results_base / "all_experiments_raw.json", "w", encoding="utf-8") as f:
        json.dump(experiment_records, f, indent=2)

    logger.info("All experiments completed. Total runs recorded: %d", len(experiment_records))
    return experiment_records


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run load and consistency experiments")
    parser.add_argument("--config", type=str, default="experiments/config.yaml", help="Path to config yaml")
    parser.add_argument("--smoke", action="store_true", help="Run short smoke test suite")
    parser.add_argument("--quick", action="store_true", help="Run quick matrix")
    args = parser.parse_args()

    execute_matrix(config_path=Path(args.config), smoke=args.smoke, quick=args.quick)
